import datetime
from typing import Dict, Any, List

class EarlyWarningService:
    def __init__(self):
        pass

    def evaluate_location_alerts(self, risk_data: Dict[str, Any], weather_data: Dict[str, Any], location: Dict[str, Any]) -> List[Dict[str, Any]]:
        """
        Generates risk notifications when experimental criteria are met across horizons (6h, 12h, 24h, 48h, 70h).
        Includes:
        - Location and coordinates
        - Forecast horizon and valid time
        - Estimated risk level
        - Factors contributing to the estimate
        - Data quality and limitations
        - Recommended precautionary information (NDMA/SDRF aligned)
        - Link to official warning source
        """
        alerts = []
        now = datetime.datetime.now(datetime.timezone.utc)
        horizons = risk_data.get("horizons", {})

        for h_key, h_data in horizons.items():
            lead_hours = h_data["lead_time_hours"]
            score = h_data["terrain_aware_risk_score"]
            category = h_data["risk_category"]
            rain_val = h_data["accumulated_rainfall_mm"]
            
            # Trigger alert condition: Score >= 0.55 (High or Severe) or severe rain
            if score >= 0.55 or rain_val >= 64.5:
                valid_time = (now + datetime.timedelta(hours=lead_hours)).strftime("%Y-%m-%d %H:00 UTC")
                
                # Precautionary advisory based on lead time & severity
                advisory = self._get_precautionary_advisory(lead_hours, score, location)
                
                alert_obj = {
                    "alert_id": f"ALERT-{location['id']}-{lead_hours}H-{now.strftime('%Y%m%d%H')}",
                    "location_id": location["id"],
                    "location_name": location["name"],
                    "state": location["state"],
                    "district": location["district"],
                    "coordinates": {
                        "latitude": location["latitude"],
                        "longitude": location["longitude"]
                    },
                    "critical_corridor": location.get("critical_corridor", "General Road Network"),
                    "forecast_horizon": f"+{lead_hours} Hours",
                    "lead_hours": lead_hours,
                    "valid_time": valid_time,
                    "risk_score": score,
                    "risk_category": category,
                    "alert_code": h_data["alert_code"],
                    "contributing_factors": {
                        "accumulated_rainfall": f"{rain_val} mm in {lead_hours}h window",
                        "antecedent_saturation_72h": f"{weather_data.get('antecedent_rainfall', {}).get('past_72h_mm', 0)} mm prior accumulation",
                        "slope_steepness": f"{location.get('slope_deg')}° ({location.get('geomorphology', 'Steep relief')})",
                        "gsi_susceptibility": location.get("gsi_susceptibility", "High"),
                        "attribution_breakdown": h_data["factor_attribution"]
                    },
                    "data_quality_and_limitations": {
                        "meteorological_source": weather_data.get("data_source"),
                        "is_fallback_active": weather_data.get("is_fallback", False),
                        "spatial_resolution": weather_data.get("spatial_resolution"),
                        "missing_data_status": weather_data.get("missing_data_status"),
                        "scientific_caveat": "Research prototype based on empirical precipitation-terrain fusion. Lead times up to 70 hours represent model projections and are subject to atmospheric NWP divergence."
                    },
                    "recommended_precautionary_action": advisory,
                    "official_warning_links": [
                        {
                            "authority": "India Meteorological Department (IMD) - Mausam",
                            "url": "https://mausam.imd.gov.in"
                        },
                        {
                            "authority": "Geological Survey of India (GSI) - Landslide EWS Portal",
                            "url": "https://bhukosh.gsi.gov.in"
                        },
                        {
                            "authority": "National Disaster Management Authority (NDMA) Guidelines",
                            "url": "https://ndma.gov.in"
                        }
                    ],
                    "prototype_disclaimer": "EXPERIMENTAL PROTOTYPE NOTICE: Generated by MHTC-EWS (SIH 2026 PS 26001). This is a research prototype, NOT an official government emergency alert. Do not use for standalone life-safety evacuation orders."
                }
                alerts.append(alert_obj)

        return alerts

    def _get_precautionary_advisory(self, lead_hours: int, score: float, location: Dict[str, Any]) -> Dict[str, Any]:
        corridor = location.get("critical_corridor", "Arterial Highway")
        
        if lead_hours <= 12:
            if score >= 0.75:
                level = "Immediate Action Protocol (Level 4)"
                actions = [
                    f"Immediate precautionary transit halt along vulnerable segments of {corridor}.",
                    "Mobilize district quick response teams (SDRF/NDRF) to pre-designated staging locations.",
                    "Advise residents in toe-slope and cliffside dwellings to move to designated community shelters.",
                    "Monitor culverts and mountain torrent discharges for rapid mudflow or debris blockages."
                ]
            else:
                level = "Heightened Vigilance Protocol (Level 3)"
                actions = [
                    f"Deploy highway patrol and spotters along {corridor} to report initial tension cracks or rockfall.",
                    "Issue travel advisories recommending non-essential journeys be deferred during night hours.",
                    "Verify emergency earthmoving equipment and heavy excavators are fueled and ready."
                ]
        elif lead_hours <= 24:
            level = "Preparedness & Staging Protocol (Level 2)"
            actions = [
                f"Inform district disaster management officers (DDMA) of projected slope saturation along {corridor}.",
                "Check drainage cleared along critical slope cuts and retaining walls.",
                "Ensure local emergency broadcast networks are primed for IMD nowcast updates."
            ]
        else: # 48 to 70 hours
            level = "Medium-Range Monitoring & Resource Allocation (Level 1)"
            actions = [
                "Track synoptic numerical weather model updates every 6 hours for potential storm path shifts.",
                f"Identify vulnerable critical infrastructure nodes along {corridor}.",
                "Keep emergency fuel, satellite communications, and medical supplies stocked at sub-divisional outposts."
            ]

        return {
            "protocol_level": level,
            "target_corridor": corridor,
            "action_items": actions,
            "guideline_standard": "Aligned with NDMA National Disaster Management Guidelines: Management of Landslides and Snow Avalanches"
        }
